// `npm run encryption:fields`: write src/lib/encrypted-fields.generated.ts from the @encrypted
// comments in prisma/schema.prisma. Run after changing which fields are encrypted.
import { readFileSync, writeFileSync } from "node:fs";
import { parseEncryptedFields } from "../src/lib/encrypted-fields";

const map = parseEncryptedFields(readFileSync("prisma/schema.prisma", "utf8"));
const out = `// Generated by \`npm run encryption:fields\` from the @encrypted comments in prisma/schema.prisma – do not edit.
import type { FieldMap } from "./encrypted-fields";

export const FIELD_MAP: FieldMap = ${JSON.stringify(map, null, 2)};
`;
writeFileSync("src/lib/encrypted-fields.generated.ts", out);
console.log("Encrypted fields:", Object.entries(map.fields).map(([m, f]) => Object.entries(f).map(([k, v]) => `${m}.${k} (${v})`)).flat().join(", ") || "none");
